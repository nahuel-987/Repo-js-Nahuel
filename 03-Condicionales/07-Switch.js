let dia = 3;

switch (dia){
    case 1:
        console.log("lunes");
    break;

    case 2:
        console.log("Martes");
    break;

    case 3:
        console.log("Miercoles");
    break;

    case 4:
        console.log("Jueves");
    break;

    case 5:
        console.log("viernes");
    break;

    default:
        console.log("Dia incorrecto");
}